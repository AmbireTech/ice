#!/usr/bin/env python3
"""Write src/parts/stm32u585Pins.ts from ST's own pin database.

    python3 scripts/genStm32Pins.py

Source: scripts/ref/STM32U585VITxQ.xml, copied verbatim from
github.com/STMicroelectronics/STM32_open_pin_data (mcu/STM32U585VITxQ.xml), the
same data STM32CubeMX uses. Nothing in the generated map is typed by hand: the
U585 has 100 pins and a transcription slip here is the class of defect that
shipped the Nano with another chip's pin map.

Label = the port name (PE2, PC14 ...); power pins repeat in the package, so they
get their pin number appended (VDD_11, VSS_10 ...).
"""
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "ref/STM32U585VITxQ.xml"
OUT = HERE.parent / "src/parts/stm32u585Pins.ts"

root = ET.parse(SRC).getroot()
tag = lambda e: e.tag.split("}")[1]
pins = [e for e in root if tag(e) == "Pin"]
names = [p.attrib["Name"].split("-")[0].split(" ")[0].replace("+", "P") for p in pins]
dup = {n for n in names if names.count(n) > 1}
lines = []
for p, n in zip(pins, names):
    pos = p.attrib["Position"]
    n = n.replace("+", "P")
    label = f"{n}_{pos}" if n in dup else n
    sigs = sorted({s.attrib["Name"] for s in p if tag(s) == "Signal" and s.attrib["Name"] != "GPIO"})
    lines.append(f'  pin{pos}: "{label}", // {p.attrib["Name"]} [{p.attrib["Type"]}] {" ".join(sigs)}'.rstrip())
OUT.write_text(
    "/**\n"
    " * STM32U585VIT6Q (LQFP100, SMPS variant) pin map — GENERATED by\n"
    " * scripts/genStm32Pins.py from ST's STM32_open_pin_data (STM32U585VITxQ.xml).\n"
    " * Do not edit by hand. Comments list each pin's alternate functions.\n"
    " */\n"
    "export const STM32U585_PINS = {\n" + "\n".join(lines) + "\n} as const\n")
print(f"wrote {OUT} ({len(pins)} pins)")
